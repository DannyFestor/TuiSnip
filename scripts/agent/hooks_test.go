func TestGuardCommand(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		command  string
		wantCode int
	}{
		{
			name:     "passes a commit whose message looks like shell",
			command:  `git commit -m "a -> b; --no-verify"`,
			wantCode: exitPass,
		},
		{name: "passes a push to a branch", command: "git add . && git push -u origin feature", wantCode: exitPass},
		{name: "passes stderr redirected to stdout", command: "go test ./... 2>&1 | tail -5", wantCode: exitPass},
		{
			name:     "passes writes to /dev/null and /tmp",
			command:  "echo x >/dev/null; echo y > /tmp/out",
			wantCode: exitPass,
		},
		{name: "passes writes to TMPDIR", command: `echo x >> "$TMPDIR/out"`, wantCode: exitPass},
		{name: "passes a heredoc read by a command", command: "wc -l <<'EOF'\na > b\nEOF", wantCode: exitPass},
		{name: "passes sed without in-place", command: "sed -n 1,5p main.go", wantCode: exitPass},
		{
			name:     "passes an interpreter that only reads",
			command:  `python3 -c 'print(open("go.mod").read())'`,
			wantCode: exitPass,
		},
		{name: "passes reading core.hooksPath", command: "git config --get core.hooksPath", wantCode: exitPass},
		{name: "passes unstaging the whole tree", command: "git restore --staged .", wantCode: exitPass},
		{
			name:     "passes a commit whose message mentions LEFTHOOK",
			command:  `git commit -m "docs: deny LEFTHOOK=0"`,
			wantCode: exitPass,
		},
		{name: "denies LEFTHOOK=0 before a command", command: "LEFTHOOK=0 git commit -m x", wantCode: exitDeny},
		{name: "denies exporting LEFTHOOK", command: "export LEFTHOOK=false && git push", wantCode: exitDeny},
		{
			name:     "denies LEFTHOOK_EXCLUDE through env",
			command:  "env LEFTHOOK_EXCLUDE=lint git push",
			wantCode: exitDeny,
		},
		{
			name:     "denies LEFTHOOK_CONFIG",
			command:  "LEFTHOOK_CONFIG=/tmp/none.yml git commit -m x",
			wantCode: exitDeny,
		},
		{name: "denies commit -n", command: "git commit -nm wip", wantCode: exitDeny},
		{name: "denies --no-verify", command: "git push --no-verify", wantCode: exitDeny},
		{
			name:     "denies overriding core.hooksPath",
			command:  "git -c core.hooksPath=/dev/null commit -m x",
			wantCode: exitDeny,
		},
		{name: "denies setting core.hooksPath", command: "git config core.hooksPath .nohooks", wantCode: exitDeny},
		{name: "denies push -f", command: "git push -f origin feature", wantCode: exitDeny},
		{name: "denies a +refspec", command: "git push origin +feature", wantCode: exitDeny},
		{name: "denies a push to main", command: "git push origin HEAD:main", wantCode: exitDeny},
		{name: "denies reset --hard", command: "git reset --hard", wantCode: exitDeny},
		{name: "denies clean -f", command: "git clean -fdx", wantCode: exitDeny},
		{name: "denies a whole-tree checkout", command: "git checkout -- .", wantCode: exitDeny},
		{name: "denies a whole-tree restore", command: "git restore .", wantCode: exitDeny},
		{name: "denies stash drop", command: "git stash drop", wantCode: exitDeny},
		{name: "denies stash clear", command: "git -C . stash clear", wantCode: exitDeny},
		{name: "denies sed -i", command: "sed -i '' 's/a/b/' main.go", wantCode: exitDeny},
		{name: "denies perl -pi", command: "perl -pi -e 's/a/b/' main.go", wantCode: exitDeny},
		{name: "denies awk -i inplace", command: "awk -i inplace 1 main.go", wantCode: exitDeny},
		{name: "denies a redirect into the repo", command: "echo x > main.go", wantCode: exitDeny},
		{name: "denies tee into the repo", command: "echo x | tee -a main.go", wantCode: exitDeny},
		{
			name:     "denies an interpreter writing a file",
			command:  "python3 - <<'EOF'\nopen('main.go', 'w').write('x')\nEOF",
			wantCode: exitDeny,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			box := newSandbox(t)

			got := box.run(t, tt.command, "guard-command.sh")

			assert.Equal(t, tt.wantCode, got.code, got.stderr)
		})
	}

	t.Run("denies a bare push from main", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.git(t, "switch", "--quiet", "main")

		got := box.run(t, "git push", "guard-command.sh")

		assert.Equal(t, exitDeny, got.code)
	})
}
