func TestOpenCodeFixtures(t *testing.T) {
	t.Parallel()

	t.Run("patch-paths lists every path an apply_patch touches", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		call := decode[opencodeToolCall](t, box.fixture(t, "opencode", "apply-patch.json"))

		got := box.run(t, call.Args.PatchText, "patch-paths.sh")

		assert.Equal(t, strings.Join([]string{
			"internal/domain/snippet.go",
			"internal/domain/tag.go",
			"internal/domain/old.go",
			"internal/adapters/sqlite/sqlcgen/old.go",
			"internal/domain/unused.go",
		}, "\n")+"\n", got.stdout)
	})

	t.Run("guard-command denies a bash call that skips hooks", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		call := decode[opencodeToolCall](t, box.fixture(t, "opencode", "bash-no-verify.json"))

		got := box.run(t, call.Args.Command, "guard-command.sh")

		assert.Equal(t, exitDeny, got.code)
		assert.Contains(t, got.stderr, "--no-verify")
	})
}

