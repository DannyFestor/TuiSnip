func TestClaudeAdapter_PostEdit(t *testing.T) {
	t.Parallel()

	t.Run("skips files that are not Go", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)

		got := box.adapter(t, "claude", "post-edit", "post-write-readme.json")

		assert.Equal(t, exitPass, got.code)
		assert.Empty(t, box.stubCalls(t))
	})

	t.Run("formats the file and vets its package", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.write(t, "pkg/clip/clip.go", goFile)

		got := box.adapter(t, "claude", "post-edit", "post-edit-go.json")

		assert.Equal(t, exitPass, got.code, got.stderr)
		assert.Equal(
			t,
			[]string{"golangci-lint fmt pkg/clip/clip.go", "go vet -tags feature,e2e ./pkg/clip"},
			box.stubCalls(t),
		)
	})

	t.Run("reports vet findings to the agent", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.write(t, "pkg/clip/clip.go", goFile)
		box.failStub("go vet")

		got := box.adapter(t, "claude", "post-edit", "post-edit-go.json")

		assert.Equal(t, exitDeny, got.code)
		assert.Contains(t, got.stderr, "go vet failed")
	})
}

func TestClaudeAdapter_Stop(t *testing.T) {
	t.Parallel()

	t.Run("passes without Go changes and runs nothing", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)

		got := box.adapter(t, "claude", "stop", "stop.json")

		assert.Equal(t, exitPass, got.code)
		assert.Empty(t, box.stubCalls(t))
	})

	t.Run("checks changed packages and skips an unchanged diff", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.write(t, "pkg/clip/clip.go", goFile)

		first := box.adapter(t, "claude", "stop", "stop.json")
		second := box.adapter(t, "claude", "stop", "stop.json")

		assert.Equal(t, exitPass, first.code, first.stderr)
		assert.Equal(t, exitPass, second.code, second.stderr)
		assert.Equal(t, []string{
			"go build ./...",
			"go-arch-lint check",
			"golangci-lint run ./pkg/clip",
			"go test -short -race ./pkg/clip",
		}, box.stubCalls(t))
	})

	t.Run("leaves tagged test packages out of go test", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.write(t, "test/feature/capture_test.go", "//go:build feature\n\npackage feature_test\n")

		got := box.adapter(t, "claude", "stop", "stop.json")

		assert.Equal(t, exitPass, got.code, got.stderr)
		assert.NotContains(t, box.stubCalls(t), "go test -short -race ./test/feature")
	})

	t.Run("blocks a failing build until the cap, then lets the agent stop", func(t *testing.T) {
		t.Parallel()
		box := newSandbox(t)
		box.write(t, "pkg/clip/clip.go", goFile)
		box.failStub("go build")

		for range maxBlocks {
			blocked := box.adapter(t, "claude", "stop", "stop.json")
			require.Equal(t, exitDeny, blocked.code)
			assert.Contains(t, blocked.stderr, "go build failed")
		}

		released := box.adapter(t, "claude", "stop", "stop.json")

		assert.Equal(t, exitPass, released.code)
		assert.Contains(t, decode[claudeOutput](t, released.stdout).SystemMessage, "go build failed")
	})
}

func TestAntigravityAdapter_Pre(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name         string
		fixture      string
		wantDecision string
		wantReason   string
	}{
		{
			name:         "denies generator output",
			fixture:      "pre-write-sqlcgen.json",
			wantDecision: "deny",
			wantReason:   "make generate-sql",
		},
		{
			name:         "asks before editing a guardrail",
			fixture:      "pre-replace-mise.json",
			wantDecision: "ask",
			wantReason:   "toolchain",
		},
		{name: "answers ask for a clean command", fixture: "pre-run-command-status.json", wantDecision: "ask"},
		{
			name:         "denies a destructive command",
			fixture:      "pre-run-command-reset.json",
			wantDecision: "deny",
			wantReason:   "reset --hard",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			box := newSandbox(t)

			got := box.adapter(t, "antigravity", "pre", tt.fixture)

			require.Equal(t, exitPass, got.code, got.stderr)

			decision := decode[antigravityOutput](t, got.stdout)
			assert.Equal(t, tt.wantDecision, decision.Decision)

			if tt.wantReason == "" {
				assert.Nil(t, decision.Reason)

				return
			}

			require.NotNil(t, decision.Reason)
			assert.Contains(t, *decision.Reason, tt.wantReason)
		})
	}
}

func TestAntigravityAdapter_PostThenPreInvocation(t *testing.T) {
	t.Parallel()

	box := newSandbox(t)
	box.write(t, "pkg/clip/clip.go", goFile)
	box.failStub("go vet")

	post := box.adapter(t, "antigravity", "post", "post-replace-go.json")
	injected := box.adapter(t, "antigravity", "pre-invocation", "pre-invocation.json")
	drained := box.adapter(t, "antigravity", "pre-invocation", "pre-invocation.json")

	assert.JSONEq(t, "{}", post.stdout)

	steps := decode[antigravityOutput](t, injected.stdout).InjectSteps
	require.Len(t, steps, 1)
	assert.Contains(t, steps[0].EphemeralMessage, "go vet failed")
	assert.JSONEq(t, "{}", drained.stdout)
}

